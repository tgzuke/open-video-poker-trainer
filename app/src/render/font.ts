/** Glyph rows as booleans; unknown characters render as '?'. */
export const GLYPHS: Record<string, boolean[][]> = Object.fromEntries(
  Object.entries(G).map(([ch, s]) => [ch, s.split(" ").map((row) => [...row].map((c) => c === "#"))]),
);

export function glyph(ch: string): boolean[][] {
  return GLYPHS[ch.toUpperCase()] ?? GLYPHS["?"];
}

export function textWidth(text: string, scale = 1): number {
  return text.length === 0 ? 0 : (text.length * ADVANCE - 1) * scale;
}

